#!/bin/bash
# Builds Lifelog for iPhone and installs it on a connected / paired iPhone.
#   phone/build.sh                 build + install on your iPhone
#   phone/build.sh --sim           just compile for the simulator (no signing, no config needed)
#
# Settings: environment variables win, then ~/Lifelog/config.json (cloud/deploy.sh writes the cloud ones), then defaults.
#   LIFELOG_TEAM       / phoneTeam      your Apple developer team id (required to install on a device)
#   LIFELOG_BUNDLE_ID  / phoneBundleId  bundle id; default lifelog.<team>.phone (must be unique to your team)
#   LIFELOG_CLOUD_URL  / cloudUrl       the Worker URL
#   LIFELOG_PHONE_TOKEN/ phoneToken     the phone's upload-only token
#   LIFELOG_IPHONE                      device id, if more than one iPhone is paired
# The URL and token are compiled into Sources/Secrets.swift, which is gitignored (see Secrets.example.swift).
set -euo pipefail
cd "$(dirname "$0")"
CONFIG="${LIFELOG_DIR:-$HOME/Lifelog}/config.json"
SIM=0; [ "${1:-}" = "--sim" ] && SIM=1

command -v python3 >/dev/null || { echo "python3 not found (xcode-select --install)" >&2; exit 1; }
command -v xcodebuild >/dev/null && xcodebuild -version >/dev/null 2>&1 \
  || { echo "Xcode not found — install Xcode from the App Store, then: sudo xcode-select -s /Applications/Xcode.app" >&2; exit 1; }
if ! command -v xcodegen >/dev/null; then
  command -v brew >/dev/null || { echo "xcodegen not found — install it (brew install xcodegen)" >&2; exit 1; }
  brew install xcodegen
fi

cfg() { [ -f "$CONFIG" ] && python3 -c "import json,sys; print(json.load(open(sys.argv[1])).get(sys.argv[2]) or '')" "$CONFIG" "$1" || true; }
URL="${LIFELOG_CLOUD_URL:-$(cfg cloudUrl)}"
TOKEN="${LIFELOG_PHONE_TOKEN:-$(cfg phoneToken)}"
DEVICE_ID="$(cfg phoneDeviceId)"; DEVICE_ID="${DEVICE_ID:-iphone}"
export LIFELOG_TEAM="${LIFELOG_TEAM:-$(cfg phoneTeam)}"
BUNDLE="${LIFELOG_BUNDLE_ID:-$(cfg phoneBundleId)}"
export LIFELOG_BUNDLE_ID="${BUNDLE:-lifelog.${LIFELOG_TEAM:-local}.phone}"

if [ $SIM = 0 ]; then
  [ -n "$LIFELOG_TEAM" ] || { echo "Set LIFELOG_TEAM (or \"phoneTeam\" in $CONFIG) to your Apple developer team id" >&2; exit 1; }
  [ -n "$URL" ] && [ -n "$TOKEN" ] || { echo "No Worker URL / phone token: run cloud/deploy.sh first (or set LIFELOG_CLOUD_URL and LIFELOG_PHONE_TOKEN)" >&2; exit 1; }
fi

python3 - "$URL" "$TOKEN" "$DEVICE_ID" > Sources/Secrets.swift <<'PY'
import json, sys
url, token, device = sys.argv[1:]
print("// generated by phone/build.sh from ~/Lifelog/config.json — do not commit")
print("enum Secrets {")
print(f"    static let url = {json.dumps(url)}")
print(f"    static let token = {json.dumps(token)}")
print(f"    static let device = {json.dumps(device)}")
print("}")
PY

xcodegen generate --quiet
if [ $SIM = 1 ]; then
  xcodebuild -project LifelogPhone.xcodeproj -scheme Lifelog -destination 'generic/platform=iOS Simulator' \
    -derivedDataPath build CODE_SIGNING_ALLOWED=NO -quiet build
  echo "✓ compiled for the simulator"
  exit 0
fi
xcodebuild -project LifelogPhone.xcodeproj -scheme Lifelog -destination 'generic/platform=iOS' -derivedDataPath build \
  -allowProvisioningUpdates -quiet build
APP=build/Build/Products/Debug-iphoneos/Lifelog.app
DEVICE="${LIFELOG_IPHONE:-$(xcrun devicectl list devices 2>/dev/null | awk '/physical/ && /available/ {for(i=1;i<=NF;i++) if ($i ~ /^[0-9A-F]{8}-[0-9A-F]{16}$/) print $i}' | head -1)}"
[ -n "$DEVICE" ] || { echo "No paired iPhone found (xcrun devicectl list devices). Connect it, trust this Mac and turn on Developer Mode." >&2; exit 1; }
xcrun devicectl device install app --device "$DEVICE" "$APP" | tail -2
xcrun devicectl device process launch --device "$DEVICE" "$LIFELOG_BUNDLE_ID" >/dev/null && echo "✓ installed and launched on $DEVICE"
