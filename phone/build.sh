#!/bin/bash
# Builds Lifelog for iPhone and installs it on a connected / paired iPhone.
#   phone/build.sh                 build + install (needs LIFELOG_TEAM or "phoneTeam" in ~/Lifelog/config.json)
#   phone/build.sh --sim           just compile for the simulator (no signing)
# The Worker URL and the phone's upload-only token come from ~/Lifelog/config.json (cloud/deploy.sh writes them) and are
# compiled into Sources/Secrets.swift, which is gitignored.
set -euo pipefail
cd "$(dirname "$0")"
CONFIG="${LIFELOG_DIR:-$HOME/Lifelog}/config.json"
cfg() { python3 -c "import json; print(json.load(open('$CONFIG')).get('$1') or '')"; }
python3 - "$CONFIG" > Sources/Secrets.swift <<'PY'
import json, sys
c = json.load(open(sys.argv[1]))
q = lambda s: json.dumps(s or "")
print("// generated by phone/build.sh from ~/Lifelog/config.json — do not commit")
print("enum Secrets {")
print(f"    static let url = {q(c.get('cloudUrl'))}")
print(f"    static let token = {q(c.get('phoneToken'))}")
print(f"    static let device = {q(c.get('phoneDeviceId') or 'iphone')}")
print("}")
PY
command -v xcodegen >/dev/null || brew install xcodegen
export LIFELOG_TEAM="${LIFELOG_TEAM:-$(cfg phoneTeam)}"
xcodegen generate --quiet
if [ "${1:-}" = "--sim" ]; then
  xcodebuild -project LifelogPhone.xcodeproj -scheme Lifelog -destination 'generic/platform=iOS Simulator' \
    -derivedDataPath build CODE_SIGNING_ALLOWED=NO -quiet build
  echo "✓ compiled for the simulator"
  exit 0
fi
[ -n "$LIFELOG_TEAM" ] || { echo "Set LIFELOG_TEAM (or phoneTeam in $CONFIG) to your Apple developer team id"; exit 1; }
xcodebuild -project LifelogPhone.xcodeproj -scheme Lifelog -destination 'generic/platform=iOS' -derivedDataPath build \
  -allowProvisioningUpdates -quiet build
APP=build/Build/Products/Debug-iphoneos/Lifelog.app
DEVICE="${LIFELOG_IPHONE:-$(xcrun devicectl list devices 2>/dev/null | awk '/physical/ && /available/ {for(i=1;i<=NF;i++) if ($i ~ /^[0-9A-F]{8}-[0-9A-F]{16}$/) print $i}' | head -1)}"
[ -n "$DEVICE" ] || { echo "No paired iPhone found (xcrun devicectl list devices)"; exit 1; }
xcrun devicectl device install app --device "$DEVICE" "$APP" | tail -2
xcrun devicectl device process launch --device "$DEVICE" lifelog.example.phone >/dev/null && echo "✓ installed and launched on $DEVICE"
